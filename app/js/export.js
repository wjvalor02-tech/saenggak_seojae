// ───────── 워드 ─────────
// blocks: [{ type: 'title'|'h1'|'h2'|'meta'|'p'|'bullet'|'quote', text }]
const RUN = 'w:rFonts w:ascii="맑은 고딕" w:eastAsia="맑은 고딕" w:hAnsi="맑은 고딕"';
function para(b) {
  const lines = String(b.text ?? '').split('\n');
  const runs = lines.map((l, i) => `${i ? '<w:r><w:br/></w:r>' : ''}<w:r><w:t xml:space="preserve">${x(l)}</w:t></w:r>`).join('');
  const style = { title: 'Title', h1: 'Heading1', h2: 'Heading2', meta: 'Meta', quote: 'Quote', bullet: 'ListParagraph' }[b.type];
  const bullet = b.type === 'bullet' ? '<w:numPr><w:ilvl w:val="0"/><w:numId w:val="1"/></w:numPr>' : '';
  return `<w:p><w:pPr>${style ? `<w:pStyle w:val="${style}"/>` : ''}${bullet}</w:pPr>${runs}</w:p>`;
}
